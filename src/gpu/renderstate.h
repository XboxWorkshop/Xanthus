typedef struct _RenderStateInfo {
	const char* S;   // String representation.
	unsigned short V;    // The XDK version since which a render state was introduced (using the 5911 declarations as a base).
	TXBType T = xt_Unknown; // The Xbox data type. Defaults to xt_Unknown.
	unsigned long M; // The related push buffer method. Not always a 1-to-1 mapping. Needs push-buffer interpretation & conversion code.
	D3DRENDERSTATETYPE PC = (D3DRENDERSTATETYPE)0; // Map XBox to PC render state
	const char* N;   // XDK notes. Defaults to ''.
	unsigned short R; // The XDK version since which a render state was removed
}
RenderStateInfo;

